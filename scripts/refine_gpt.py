def create_proof_prompt(problem, goal, proof):
    full_prompt = f"""
    Here is a geometry problem:
    {problem}
    The goal is to proof:
    {goal}
    The following is a correct proof generated by a neural symbolic solver:
    {proof}
    Please reason step by step, rephrasing and extracting key steps in the above proof to generate a plain text natural language proof without step indices.
    """
    return full_prompt


