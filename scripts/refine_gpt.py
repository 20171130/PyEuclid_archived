data_json_list = ["informalized_dataset/rank_5/problem_48/sample_0/data.json"]
image_file_list = ["informalized_dataset/rank_5/problem_48/sample_0/diagram.jpg"]
total_num = len(data_json_list)
error_list = list()
result = dict()

for idx, (data_json, image_file) in enumerate(zip(data_json_list, image_file_list)):
    print(f"{idx + 1}/{total_num}")
